import { SlashCommandBuilder, PermissionFlagsBits } from "discord.js";

export default {
    data: new SlashCommandBuilder()
        .setName("create-staff-roles")
        .setDescription("Create all Anime Genesis Studio staff roles.")
        .setDefaultMemberPermissions(PermissionFlagsBits.Administrator),

    ownerOnly: true,

    async execute(interaction) {
        const roleNames = [
            { name: "Owner", color: "Red" },
            { name: "Co-Owner", color: "Black" },
            { name: "Genesis Administrator", color: "DarkPurple" },
            { name: "Genesis Captain", color: "DarkBlue" },
            { name: "Genesis Officer", color: "Blue" },
            { name: "Genesis Helper", color: "Aqua" },
            { name: "Developer", color: "Gold" },
            { name: "Scripter", color: "Green" },
            { name: "Builder", color: "DarkGreen" },
            { name: "UI Designer", color: "Purple" },
            { name: "Modeler", color: "Grey" },
            { name: "Tester", color: "Yellow" }
        ];

        let created = [];

        for (const roleData of roleNames) {
            let role = interaction.guild.roles.cache.find(r => r.name === roleData.name);
            if (!role) {
                role = await interaction.guild.roles.create({
                    name: roleData.name,
                    color: roleData.color,
                    reason: "Generated by Genesis Bot"
                });
                created.push(roleData.name);
            }
        }

        await interaction.reply({
            content: `✅ Roles created:\n\`\`\`\n${created.join("\n")}\n\`\`\``,
            ephemeral: true
        });
    }
};
